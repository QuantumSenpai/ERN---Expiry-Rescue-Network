/**
 * Factory to construct a consistent, fully computed ProductOffer
 */
export function createProductOffer(params: {
  id: string;
  batchNumber: string;
  type: RescueTierType;
  mrp: number;
  price: number;
  daysFromNow: number;
  hoursOffset?: number;
  availability: number;
  tagline?: string;
}): ProductOffer {
  const expiryDate = getRelativeIsoDate(params.daysFromNow, params.hoursOffset || 0);
  const expiryInfo = calculateExpiryStatus(expiryDate);
  const pricing = calculatePricing(params.mrp, { sellingPrice: params.price });

  return {
    id: params.id,
    batchNumber: params.batchNumber,
    type: params.type,
    mrp: params.mrp,
    price: pricing.sellingPrice,
    discountPercent: pricing.discountPercent,
    savings: pricing.savings,
    expiryDate,
    expiryText: expiryInfo.expiryText,
    daysRemaining: expiryInfo.daysRemaining,
    availability: params.availability,
    tagline: params.tagline || expiryInfo.tierDescription,
  };
}

